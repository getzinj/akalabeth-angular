def main(stages: list) -> None:
    (OUT / 'sessions').mkdir(parents=True, exist_ok=True)

    if 'worlds' in stages:
        tables = None
        worlds = []
        for lucky in [str(number) for number in range(1, 31)] + ['0', '-1', '-7', '2.5', '1979', '65535']:
            machine = new_game(lucky)
            if tables is None:
                tables = record_tables(machine)
            worlds.append(record_world(machine, lucky))
            print('world', lucky, flush=True)
        (OUT / 'tables.json').write_text(json.dumps(tables, separators=(',', ':')) + '\n')
        (OUT / 'worlds.json').write_text(json.dumps(worlds, separators=(',', ':')) + '\n')

    if 'scenarios' in stages or 'gallery' in stages:
        for make in (SCENARIOS if 'scenarios' in stages else [session_gallery]):
            session = make()
            (OUT / 'sessions' / f"{session['name']}.json").write_text(json.dumps(session, separators=(',', ':')) + '\n')
            print('session', session['name'], len(session['steps']), flush=True)

    if 'input' in stages:
        records = [record_input(typed) for typed in INPUT_LINES]
        (OUT / 'input.json').write_text(json.dumps(records, separators=(',', ':')) + '\n')
        print('input', len(records), flush=True)

    if 'dungeons' in stages:
        worlds = json.loads((OUT / 'worlds.json').read_text())
        dungeons = []
        for world in worlds[:3]:
            machine = dungeon_machine(world['lucky'], '1')
            for tx, ty in squares(world, 4)[:3]:
                for level in range(1, 11):
                    record = record_dungeon(machine, tx, ty, level)
                    record['lucky'] = world['lucky']
                    dungeons.append(record)
            print('dungeons', world['lucky'], flush=True)
        (OUT / 'dungeons.json').write_text(json.dumps(dungeons, separators=(',', ':')) + '\n')

    if 'sessions' in stages or 'dungeon-sessions' in stages:
        makers = [session_creation, session_overworld, session_knighthood,
                  lambda: session_dungeon('1', 'F', 'FFFFRASBMQ', 11, 150),
                  lambda: session_dungeon('2', 'M', 'FFFFMMQ', 12, 150),
                  lambda: session_dungeon('5', 'F', 'FFFFFRQ', 13, 250)]
        for make in makers[3:] if 'dungeon-sessions' in stages else makers:
            session = make()
            (OUT / 'sessions' / f"{session['name']}.json").write_text(json.dumps(session, separators=(',', ':')) + '\n')
            print('session', session['name'], len(session['steps']), flush=True)


