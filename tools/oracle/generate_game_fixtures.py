class Recorder:
    def __init__(self, machine: Apple2) -> None:
        self.machine = machine
        self.steps = []
        self.previous_text = [''] * 24
        self.previous_inverse = [''] * 24
        self.previous_mode = None
        self.previous_hires = None
        self.errors = []
        self.setups = []
        machine.on_key = self.on_key
        machine.on_error = self.errors.append

    def state(self) -> dict:
        machine = self.machine
        record = {}
        text = machine.text_lines()
        inverse = machine.inverse_mask()
        changed = {row: text[row] for row in range(24) if text[row] != self.previous_text[row]}
        if changed:
            record['text'] = changed
        changed_inverse = {row: inverse[row] for row in range(24) if inverse[row] != self.previous_inverse[row]}
        if changed_inverse:
            record['inverse'] = changed_inverse
        mode = ('GRAPHICS' if machine.graphics else 'TEXT') + ('+MIXED' if machine.mixed else '') + \
               ('+HIRES' if machine.hires else '') + ('+PAGE2' if machine.page2 else '')
        if mode != self.previous_mode:
            record['mode'] = mode
        hires = machine.hires_page()
        if hires != self.previous_hires:
            record['hires'] = base64.b64encode(zlib.compress(hires, 9)).decode('ascii')
        if self.errors:
            record['errors'] = self.errors[:]
            self.errors.clear()
        self.previous_text, self.previous_inverse, self.previous_mode, self.previous_hires = text, inverse, mode, hires
        return record

    def on_key(self, key: int) -> None:
        record = self.state()
        record['key'] = key | 0x80
        self.steps.append(record)

    def finish(self) -> list:
        self.steps.append(self.state())
        self.machine.on_key = None
        return self.steps


def path_to(world: dict, start: list, kind: int) -> tuple:
    """Overworld keys along a shortest walk to the nearest square of a kind, round the mountains,
    and the square it ends on."""
    start = [int(value) for value in start]
    moves = [(0, -1, NORTH), (1, 0, EAST), (-1, 0, WEST), (0, 1, SOUTH)]
    seen = {tuple(start): []}
    queue = deque([tuple(start)])
    while queue:
        x, y = queue.popleft()
        if world['terrain'][x][y] == kind and [x, y] != start:
            return seen[(x, y)], [x, y]
        for dx, dy, key in moves:
            nx, ny = x + dx, y + dy
            if (nx, ny) not in seen and world['terrain'][nx][ny] != 1:
                seen[(nx, ny)] = seen[(x, y)] + [key]
                queue.append((nx, ny))
    raise ValueError(f'no square of kind {kind} reachable')


def started_session(lucky: str, level: str, stats_answers: str, kind: str, shopping: str):
    machine = typed_machine()
    press(machine, 'RUN\r')
    recorder = Recorder(machine)
    press(machine, lucky + '\r', level + '\r', stats_answers, kind, shopping)
    world = record_world(machine, lucky)
    return machine, recorder, world


def dungeon_policy(machine: Apple2, rng: random.Random, kind: str, keys: int) -> None:
    for _ in range(keys):
        screen = screen_text(machine)
        if 'HIT ESC KEY' in screen:
            press(machine, ESCAPE)
            return
        if 'TO CONT' in screen or 'TO CONTINUE' in screen:
            press(machine, RETURN)
            continue
        roll = rng.random()
        if roll < 0.40:
            press(machine, FORWARD)
        elif roll < 0.55:
            press(machine, rng.choice([TURN_RIGHT, TURN_LEFT, TURN_AROUND]))
        elif roll < 0.62:
            press(machine, 'X')
        elif roll < 0.92:
            weapon = rng.choice('RASBM' if kind == 'F' else 'ASM')
            press(machine, 'A', weapon)
            if weapon == 'A':
                press(machine, rng.choice('TS'))
            if weapon == 'M' and kind == 'M' and 'CHOICE' in screen_text(machine):
                press(machine, rng.choice('1234'))
        elif roll < 0.96:
            press(machine, ' ')
        else:
            press(machine, 'S', RETURN)


