"""Records Akalabeth running on the real Apple II+ ROMs, for the port's differential specs.

Usage: ./build-rom.sh && ./fetch-listing.sh && python3 generate_game_fixtures.py

Writes src/app/port/fixtures/:
  tables.json       the perspective tables XX% YY% PER% LD% CD% FT% LAD% (they do not depend on the seed)
  worlds.json       per lucky number: the 20x20 terrain, the starting square and the rolled stats
  dungeons.json     per lucky number, dungeon square and level: DNG%, the float DNG array line 520
                    writes, monster positions and hit points
  sessions/*.json   scripted games, one screen state per key

The program is loaded at $4001, above the hi-res page it draws on, as the original disk had to.
"""
import base64
import hashlib
import json
import pickle
import random
import sys
import zlib
from collections import deque
from pathlib import Path

from apple2_machine import Apple2
from listing import program_text

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[1] / 'src' / 'app' / 'port' / 'fixtures'
TYPED_PREFIX = 'typed-program-'

RETURN, RIGHT, LEFT, ESCAPE, CTRL_C = 0x0D, 0x15, 0x08, 0x1B, 0x03
NORTH, EAST, WEST, SOUTH = RETURN, RIGHT, LEFT, ord('/')
FORWARD, TURN_RIGHT, TURN_LEFT, TURN_AROUND = RETURN, RIGHT, LEFT, ord('/')


def packed_to_number(packed: str) -> float:
    data = bytes.fromhex(packed)
    if data[0] == 0:
        return 0.0
    mantissa = ((data[1] | 0x80) << 24) | (data[2] << 16) | (data[3] << 8) | data[4]
    value = mantissa * 2.0 ** (data[0] - 160)
    return -value if data[1] & 0x80 else value


def grid(array: dict) -> list:
    """Applesoft stores the first subscript fastest; return rows indexed [first][second]."""
    first, second = array['extents']
    return [[array['values'][x + first * y] for y in range(second)] for x in range(first)]


# --- machine lifecycle ---

def typed_machine() -> Apple2:
    machine = Apple2()
    digest = hashlib.sha256('\n'.join(program_text()).encode()).hexdigest()[:16]
    typed = HERE / 'rom' / f'{TYPED_PREFIX}{digest}.pkl'
    if typed.exists():
        machine.restore(pickle.loads(typed.read_bytes()))
    else:
        machine.reset()
        machine.run_until_idle(limit=20_000_000)
        machine.type_text('POKE 103,1:POKE 104,64:POKE 16384,0:NEW\r')
        machine.type_text('\r'.join(program_text()) + '\r')
        typed.write_bytes(pickle.dumps(machine.snapshot()))
    return machine


def press(machine: Apple2, *keys) -> None:
    for key in keys:
        if isinstance(key, str):
            machine.keys.extend(ord(character) for character in key)
        else:
            machine.keys.append(key)
    machine.run_until_idle()


def screen_text(machine: Apple2) -> str:
    return '\n'.join(machine.text_lines())


def new_game(lucky: str, level: str = '1', stats_answers: str = 'Y', kind: str = 'F', shopping: str = 'Q') -> Apple2:
    machine = typed_machine()
    press(machine, 'RUN\r', lucky + '\r', level + '\r', stats_answers, kind, shopping)
    return machine


# --- worlds and tables ---

def record_tables(machine: Apple2) -> dict:
    arrays = machine.arrays()
    return {name: arrays[key]['values'] if len(arrays[key]['extents']) == 1 else grid(arrays[key])
            for name, key in [('XX', 'XX%'), ('YY', 'YY%'), ('PER', 'PE%'), ('LD', 'LD%'), ('CD', 'CD%'),
                              ('FT', 'FT%'), ('LAD', 'LA%')]}


def record_world(machine: Apple2, lucky: str) -> dict:
    arrays = machine.arrays()
    variables = machine.simple_variables()
    return {
        'lucky': lucky,
        'terrain': grid(arrays['TE%']),
        'start': [packed_to_number(variables['TX']), packed_to_number(variables['TY'])],
        'stats': [packed_to_number(value) for value in arrays['C']['values']],
        'statsPacked': arrays['C']['values'],
    }


# --- dungeons, generated by the program's own GOSUB 500 in direct mode ---
# Ctrl-C cannot reach direct mode once the program runs: ONERR GOTO 4 catches it and restarts.
# So the dungeon generator is called before RUN, with the arrays it uses dimensioned as line 20
# and line 60041 do, and the variables it reads set as play would leave them.

def dungeon_machine(lucky: str, level_of_play: str) -> Apple2:
    machine = typed_machine()
    press(machine, f'DIM DN%(10,10),ML%(10,1),MZ%(10,1):LN={lucky}:LP={level_of_play}\r')
    return machine


def record_dungeon(machine: Apple2, tx: int, ty: int, level: int) -> dict:
    press(machine, f'PX=1:PY=1:TX={tx}:TY={ty}:IN={level}:GOSUB 500\r')
    arrays = machine.arrays()
    variables = machine.simple_variables()
    record = {
        'square': [tx, ty],
        'level': level,
        'dng': grid(arrays['DN%']),
        'monsterAt': grid(arrays['ML%']),
        'monster': grid(arrays['MZ%']),
        'count': packed_to_number(variables['NM']),
    }
    if 'DN' in arrays:
        record['floatDng'] = grid(arrays['DN'])
    return record


def squares(world: dict, kind: int) -> list:
    return [[x, y] for x in range(21) for y in range(21) if world['terrain'][x][y] == kind]


